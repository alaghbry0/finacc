#!/usr/bin/env bun
/**
 * gen-migrations-manifest.mjs — يولّد src/db/migrations-manifest.ts من ملفات drizzle/*.sql.
 *
 * لكل ملف هجرة: version = البادئة الرقمية لاسم الملف، name = اسم الملف بلا امتداد،
 * statements = [نص SQL كاملاً كسلسلة واحدة] — يُنفَّذ عبر adapter.exec() الذي يتعامل
 * مع متعدد الجمل وأجسام التريغرات (BEGIN...END;) بشكل صحيح دون تقسيم هش على «;».
 *
 * التشغيل بعد أي `drizzle-kit generate`:
 *   bun scripts/gen-migrations-manifest.mjs
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const drizzleDir = join(here, '..', 'drizzle');
const outPath = join(here, '..', 'src', 'db', 'migrations-manifest.ts');

const files = readdirSync(drizzleDir)
  .filter((f) => f.endsWith('.sql'))
  .sort((a, b) => numericPrefix(a) - numericPrefix(b) || a.localeCompare(b));

if (files.length === 0) {
  throw new Error(`لا توجد ملفات هجرة في ${drizzleDir} — شغّل drizzle-kit generate أولاً`);
}

const migrations = files.map((file) => {
  const version = numericPrefix(file);
  if (!Number.isInteger(version)) {
    throw new Error(`اسم ملف الهجرة يجب أن يبدأ ببادئة رقمية: ${file}`);
  }
  const name = file.replace(/\.sql$/, '');
  const statements = [readFileSync(join(drizzleDir, file), 'utf8')];
  return { version, name, statements };
});

// فحص رتابة الأرقام
for (let i = 1; i < migrations.length; i++) {
  if (migrations[i].version <= migrations[i - 1].version) {
    throw new Error(`أرقام الهجرات غير رتيبة: ${migrations[i - 1].name} ثم ${migrations[i].name}`);
  }
}

const body = JSON.stringify(migrations, null, 2);

const content = `// AUTO-GENERATED by scripts/gen-migrations-manifest.mjs — لا تُعدَّل يدوياً.
// المصدر: drizzle/*.sql (بترتيب البادئة الرقمية). أُعيد التوليد بعد كل drizzle-kit generate.
// كل هجرة = سلسلة SQL واحدة تُنفَّذ عبر adapter.exec() (يفهم الجمل المتعددة وأجسام التريغرات).

export interface MigrationFile {
  /** رقم إصدار الهجرة = البادئة الرقمية لاسم الملف */
  version: number;
  /** اسم الملف بلا امتداد */
  name: string;
  /** نص SQL كاملاً كسلسلة واحدة (تُنفَّذ عبر exec) */
  statements: string[];
}

export const MIGRATIONS: MigrationFile[] = ${body};
`;

writeFileSync(outPath, content);
console.log(
  `[gen-migrations-manifest] ${migrations.length} هجرة → ${outPath} (` +
    migrations.map((m) => `${m.version}:${m.name}`).join(', ') +
    ')',
);

function numericPrefix(file) {
  return parseInt(file.split('_')[0] ?? '', 10);
}
