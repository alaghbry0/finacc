/** نوع القاموس */
export type ArDict = typeof ar;

/** مسارات النصوص (أوراق الشجر) — لتوثيق مفاتيح t() آلياً */
type Join<K, P> = K extends string ? (P extends string ? `${K}.${P}` : never) : never;
type Leaves<T> = {
  [K in keyof T & string]: T[K] extends string ? K : Join<K, Leaves<T[K]>>;
}[keyof T & string];
export type ArPath = Leaves<ArDict>;

/**
 * t(path) — يقرأ نصاً من القاموس بمسار منقّط.
 * استخدام محدود للحالات الديناميكية (خرائط مفاتيح القوائم/الحالات)؛
 * ما سواها: وصول مباشر `ar.x.y` أوضح وأسرع.
 * غير موجود/ليس ورقة → يُرجَع المسار نفسه (دفاعي، لا انهيار في العرض).
 */
export function t(path: ArPath): string {
  const parts = path.split('.');
  let cur: unknown = ar;
  for (const p of parts) {
    if (cur && typeof cur === 'object' && p in (cur as Record<string, unknown>)) {
      cur = (cur as Record<string, unknown>)[p];
    } else {
      return path;
    }
  }
  return typeof cur === 'string' ? cur : path;
}

/* ============ صيغ الجمع العربية للعدّادات ============ */

/** صيغ العدّ (قوائم الأصناف/العملاء/الموردين) — {n} تُستبدل بالرقم */
export type CountForms = { zero: string; one: string; two: string; few: string; many: string };

/**
 * pluralAr — يختار صيغة العدد العربية الصحيحة:
 * صفر/واحد/اثنان مفردة، 3–10 جمع، 11+ مفرد معدود.
 */
export function pluralAr(n: number, forms: CountForms): string {
  if (n === 0) return forms.zero;
  if (n === 1) return forms.one;
  if (n === 2) return forms.two;
  const label = n >= 3 && n <= 10 ? forms.few : forms.many;
  return label.replace('{n}', String(n));
}
